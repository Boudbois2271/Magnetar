Action factoryAction(int layer, std::uint16_t key)
{
    const std::span<const Factory> table = layer == 1 ? std::span<const Factory>(kFactoryFn)
                                                      : std::span<const Factory>(kFactoryDefault);
    const auto it = std::find_if(table.begin(), table.end(), [&](const Factory &f) { return f.key == key; });
    if (it == table.end())
        throw Error("no such key");
    return it->action;
}

