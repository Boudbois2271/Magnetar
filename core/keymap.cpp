ActionKind actionKind(const Action &a)
{
    if (a == kUnbound)
        return ActionKind::Unbound;
    switch (a[0]) {
    case 0x00: return ActionKind::Key;
    case 0x01: return ActionKind::Mouse;
    case 0x02: return ActionKind::Consumer;
    case 0x03: return ActionKind::Macro;
    case 0x07: return ActionKind::System;
    case 0x08: return ActionKind::Lighting;
    case 0x09: return ActionKind::Profile;
    case 0x0d: return ActionKind::Layer;
    default: return ActionKind::Unknown;
    }
}

std::optional<KeyCombo> keyCombo(const Action &a)
{
    if (actionKind(a) != ActionKind::Key)
        return std::nullopt;
    KeyCombo c;
    c.modifiers = a[1];
    // One key sits in byte 3 when alone and in byte 2 with modifiers; with two keys the
    // first chosen is in byte 3 and the second in byte 2 (akko-capture11.txt mark 16).
    if (a[3])
        c.keys.push_back(a[3]);
    if (a[2])
        c.keys.push_back(a[2]);
    return c;
}

Action keyAction(std::uint8_t usage)
{
    return {0x00, 0x00, 0x00, usage};
}

Action comboAction(std::uint8_t modifiers, std::span<const std::uint8_t> keys)
{
    if (keys.size() > 2)
        throw Error("a shortcut has at most two keys");
    if (modifiers == 0) {
        if (keys.size() != 1)
            throw Error("a shortcut of two keys needs a modifier");
        return keyAction(keys[0]);
    }
    if (keys.empty())
        return {0x00, modifiers, 0x00, 0x00};
    if (keys.size() == 1)
        return {0x00, modifiers, keys[0], 0x00};
    return {0x00, modifiers, keys[1], keys[0]};
}

Action mouseAction(std::uint8_t button)
{
    return {0x01, button, 0x01, 0x00};
}

Action consumerAction(std::uint16_t usage)
{
    return {0x02, 0x00, static_cast<std::uint8_t>(usage >> 8), static_cast<std::uint8_t>(usage & 0xFF)};
}

Action layerAction(int layer)
{
    return {0x0d, static_cast<std::uint8_t>(layer), 0x00, 0x00};
}

std::string actionHex(const Action &a)
{
    char buf[12];
    std::snprintf(buf, sizeof buf, "%02x %02x %02x %02x", a[0], a[1], a[2], a[3]);
    return buf;
}

std::optional<Action> parseAction(const std::string &hex)
{
    Action a{};
    unsigned v[4];
    int used = 0;
    if (std::sscanf(hex.c_str(), "%2x %2x %2x %2x%n", &v[0], &v[1], &v[2], &v[3], &used) != 4 ||
        used != static_cast<int>(hex.size()) || hex.size() != 11)
        return std::nullopt;
    for (int i = 0; i < 4; ++i)
        a[i] = static_cast<std::uint8_t>(v[i]);
    return a;
}

